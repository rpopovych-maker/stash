import AppKit

struct Capture {
    var kind: ClipKind
    var text: String?
    var rtfData: Data?
    var imageData: Data?
    var filePaths: [String] = []
    var sourceBundleID: String?
    var sourceAppName: String?
    var hash: String
}

@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.apple.keychain.secure-text",
    ]

    private init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardMonitor.shared.poll() }
        }
    }

    func ignoreCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let settings = AppSettings.shared
        guard !settings.isPaused else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        if settings.ignoreConcealed, !types.isDisjoint(with: Self.skippedTypes) { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let bundleID = app?.bundleIdentifier, settings.ignoredBundleIDs.contains(bundleID) { return }

        guard var capture = read() else { return }
        capture.sourceBundleID = app?.bundleIdentifier
        capture.sourceAppName = app?.localizedName
        ClipStore.shared.insert(capture)
    }

    private func read() -> Capture? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return Capture(kind: .file, text: paths.joined(separator: "\n"), filePaths: paths, hash: ClipStore.hash(paths.map { Data($0.utf8) }))
        }

        let string = pasteboard.string(forType: .string)
        let trimmed = string?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""

        if trimmed.isEmpty || Self.isLink(trimmed), let imageData = readImage() {
            return Capture(kind: .image, imageData: imageData, hash: ClipStore.hash([imageData]))
        }

        guard let string, !trimmed.isEmpty else { return nil }

        if Self.isLink(trimmed) {
            return Capture(kind: .link, text: trimmed, hash: ClipStore.hash([Data(trimmed.utf8)]))
        }
        if Self.isColor(trimmed) {
            return Capture(kind: .color, text: trimmed, hash: ClipStore.hash([Data(trimmed.utf8)]))
        }
        let rtf = pasteboard.data(forType: .rtf)
        return Capture(kind: .text, text: string, rtfData: rtf, hash: ClipStore.hash([Data(string.utf8)]))
    }

    private func readImage() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        if let tiff = pasteboard.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
            return rep.representation(using: .png, properties: [:])
        }
        return nil
    }

    static func isLink(_ string: String) -> Bool {
        guard !string.contains(where: \.isWhitespace),
              let url = URL(string: string),
              let scheme = url.scheme?.lowercased(),
              ["http", "https"].contains(scheme),
              url.host != nil
        else { return false }
        return true
    }

    static func isColor(_ string: String) -> Bool {
        string.range(of: #"^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$"#, options: .regularExpression) != nil
    }
}
